"""Writes core/server_errors_gen.hpp: the text of every refusal code of EH3D-SERVER in the eight languages of the screen's tables.

The codes come from EH3D-SERVER/docs/error-codes.json. The eight texts of a code (English, Spanish, Italian, German, French, European Portuguese, Chinese, Japanese, the
order of lang.hpp) are the ones of the table of EH3D-ANDROID-CONTROL (app/src/main/assets/server-errors.json, itself built from the texts of EH3D-STUDIO), so the
screen, the phone app and Studio say the same words. A code the server has and the table has not is left out of the file (the screen then shows the code itself, as the
client library does), and the generator says which ones; `--strict` turns that into a failure. No text is ever invented here.

    py -3 -I tools/gen_server_errors.py            write the file
    py -3 -I tools/gen_server_errors.py --check    fail when the file is not the one the sources give (skipped when the server or the phone app is not next to this repository)
    py -3 -I tools/gen_server_errors.py --strict   fail when a code of the server has no eight texts
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GITHUB = ROOT.parent
CODES = GITHUB / "EH3D-SERVER" / "docs" / "error-codes.json"
TABLE = GITHUB / "EH3D-ANDROID-CONTROL" / "app" / "src" / "main" / "assets" / "server-errors.json"
OUT = ROOT / "core" / "server_errors_gen.hpp"
LANGS = 8


def c_string(text: str) -> str:
    """A C++ string literal with the text as UTF-8 (the same way locales_gen.hpp writes its texts)."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def header(table: dict) -> str:
    """The text of the header for a table {code: [eight texts]}; the codes are sorted so that the firmware can search by halves."""
    for code, texts in table.items():
        if not code or code != code.lower() or not all(c.isalnum() or c == "_" for c in code):
            raise ValueError(f"bad code: {code!r}")
        if len(texts) != LANGS or any(not t.strip() for t in texts):
            raise ValueError(f"{code}: eight texts are needed")
    out = ["// EH3D-NODE-HMI-GUI - core/server_errors_gen.hpp",
           "// Copyright (C) 2026 JuanenRac (Electro Hobby 3D). GPL-3.0-or-later.",
           "// Generated by tools/gen_server_errors.py from the codes of EH3D-SERVER and the table of texts of the phone app: do not edit by hand.",
           "// The codes are sorted (byte order); a row is the text of the code in en, es, it, de, fr, pt, zh and ja.",
           "#pragma once", "", "#include <cstddef>", "", "#include \"lang.hpp\"", "", "namespace hmi {", "",
           "struct ServerErrorRow {", "    const char* code;", "    Row texts;", "};", "",
           f"inline constexpr std::size_t kServerErrorCount = {len(table)};", "",
           "inline const ServerErrorRow kServerErrors[kServerErrorCount] = {"]
    for code in sorted(table):
        out.append(f"    {{{c_string(code)}, {{{', '.join(c_string(t) for t in table[code])}}}}},")
    out += ["};", "", "}  // namespace hmi", ""]
    return "\n".join(out)


def build() -> tuple[str, list]:
    """The text of the file and the codes of the server that have no eight texts."""
    codes = sorted(item["code"] for item in json.loads(CODES.read_text(encoding="utf-8")))
    have = json.loads(TABLE.read_text(encoding="utf-8"))
    table = {c: have[c] for c in codes if c in have and len(have[c]) == LANGS and all(t.strip() for t in have[c])}
    return header(table), [c for c in codes if c not in table]


def main() -> int:
    if not CODES.is_file() or not TABLE.is_file():
        print("SERVER_ERRORS=SKIP (EH3D-SERVER or EH3D-ANDROID-CONTROL is not next to this repository)")
        return 0
    text, missing = build()
    if "--strict" in sys.argv and missing:
        print("SERVER_ERRORS=FAIL (no eight texts for: " + ", ".join(missing) + ")")
        return 1
    if "--check" in sys.argv:
        current = OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") if OUT.is_file() else ""
        if current != text:
            print("SERVER_ERRORS=FAIL (core/server_errors_gen.hpp is not the one the sources give: run py -3 -I tools/gen_server_errors.py)")
            return 1
        print(f"SERVER_ERRORS=PASS ({text.count(chr(10) + '    {' + chr(34))} codes, {len(missing)} without texts)")
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(json.loads(TABLE.read_text(encoding='utf-8')))} codes in the table; no eight texts for: {', '.join(missing) or 'none'})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
