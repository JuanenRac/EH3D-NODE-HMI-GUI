#!/usr/bin/env python3
"""Compiles the names of the eight languages of the screen (locales/names.tsv) into core/locales_gen.hpp, and checks them and the font.

    python -I tools/make_locales.py            writes core/locales_gen.hpp
    python -I tools/make_locales.py --check    fails when the file is out of date, names.tsv does not hold the eight languages, or a character of the texts the
                                               screen draws is not in the font of core/font_ranges.hpp

The texts of the eight languages live in the tables of the headers (ui_text.hpp, quality.hpp...), so the folder `locales` holds only `names.tsv`: the name of
every language in itself, in the order of the selector of the screen.
Copyright (C) 2026 JuanenRac (Electro Hobby 3D). GPL-3.0-or-later.
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALES = ROOT / "locales"
GEN = ROOT / "core" / "locales_gen.hpp"
RANGES = ROOT / "core" / "font_ranges.hpp"

BASE = ["en", "es", "it", "de", "fr", "pt", "zh", "ja"]
# Files that hold text the screen draws (the literals of these files must be in the font as well).
LITERAL_FILES = ["core/ui_text.hpp", "core/quality.hpp", "core/keyboard.hpp", "main/ui.cpp"]


def key_names() -> list[str]:
    text = (ROOT / "core" / "locales.hpp").read_text(encoding="utf-8")
    block = text[text.index("kKeyNames["):text.index("};", text.index("kKeyNames["))]
    return re.findall(r'"([a-z]+\.[A-Za-z_]+)"', block)


def read_tsv(path: Path) -> dict[str, str]:
    rows: dict[str, str] = {}
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        if "\t" not in line:
            raise ValueError(f"{path.name}:{n}: no tab")
        key, value = line.split("\t", 1)
        if key in rows:
            raise ValueError(f"{path.name}:{n}: key {key} twice")
        rows[key] = value
    return rows


def languages() -> list[tuple[str, str]]:
    return [tuple(line.split("\t", 1)) for line in (LOCALES / "names.tsv").read_text(encoding="utf-8").splitlines() if line and not line.startswith("#")]  # type: ignore[misc]


def literal_chars() -> set[str]:
    """The characters of the string literals of the files that draw text."""
    chars: set[str] = set()
    # EH3D_EXTRA_LITERALS: more files (separated like a PATH) whose literals the fonts must hold too: the two touch screens share one set of fonts, so each is built with the literals of the other
    extra = [Path(p) for p in os.environ.get("EH3D_EXTRA_LITERALS", "").split(os.pathsep) if p]
    for source in [ROOT / rel for rel in LITERAL_FILES] + extra:
        text = source.read_text(encoding="utf-8")
        for lit in re.findall(r'"((?:[^"\\\n]|\\.)*)"', text):
            chars.update(re.sub(r"\\.", "", lit))
    return chars


def used_chars() -> set[str]:
    """Every character the screen can draw: printable ASCII, the literals of the code, the names of the languages."""
    chars = {chr(c) for c in range(0x20, 0x7F)}
    chars |= {c for c in literal_chars() if ord(c) >= 0x20}
    for _, name in languages():
        chars.update(name)
    return chars


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate() -> str:
    langs = languages()
    out = [f"// {ROOT.name} - core/locales_gen.hpp",
           "// Copyright (C) 2026 JuanenRac (Electro Hobby 3D). GPL-3.0-or-later.",
           "// Generated by tools/make_locales.py from the files of the folder `locales`: do not edit by hand. The eight languages of the project keep their texts in the tables of the headers, so there are no columns of texts here, only the names of the languages.",
           "#pragma once", "", "#include <cstddef>", "", "namespace hmi {", "namespace gen {", ""]
    out.append(f"inline const char* const kLangNames[{len(langs)}] = {{")
    for code, name in langs:
        out.append(f"    {c_string(name)},  // {code}")
    out.append("};")
    out += ["", "}  // namespace gen", "}  // namespace hmi", ""]
    return "\n".join(out)


def ranges_of_file() -> list[tuple[int, int]] | None:
    if not RANGES.exists():
        return None
    return [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\}", RANGES.read_text(encoding="utf-8"))]


def problems() -> list[str]:
    bad: list[str] = []
    try:
        langs = languages()
    except OSError as e:
        return [f"locales/names.tsv: {e}"]
    if [c for c, _ in langs] != BASE:
        bad.append("locales/names.tsv: the languages are en es it de fr pt zh ja, in this order")
    extra = sorted(p.name for p in LOCALES.glob("*.tsv") if p.stem != "names")
    if extra:
        bad.append(f"locales: {extra} are not languages of the project any more (only names.tsv stays)")
    ranges = ranges_of_file()
    if ranges is None:
        bad.append("core/font_ranges.hpp is missing (run tools/make_fonts.py)")
    else:
        lost = sorted(c for c in used_chars() if not any(a <= ord(c) <= b for a, b in ranges))
        if lost:
            bad.append("characters that are not in the font (run tools/make_fonts.py): " + "".join(lost[:40]))
    if not GEN.exists() or GEN.read_text(encoding="utf-8") != generate():
        bad.append("core/locales_gen.hpp is out of date (run tools/make_locales.py)")
    return bad


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="backslashreplace")
    if "--check" in sys.argv:
        bad = problems()
        for b in bad:
            print("FAIL", b)
        print("locales: " + ("PASS" if not bad else f"{len(bad)} problems"))
        return 1 if bad else 0
    GEN.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {GEN.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
